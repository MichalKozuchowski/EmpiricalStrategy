"""
03_descriptives.py: the facts that shape the empirical design.
  (a) yearly market size (after removing duplicate rows)
  (b) how often posted prices change, and in which calendar months (like Pennsylvania's renegotiation cycle?)
  (c) category shares (for nests)
Writes output/descriptives.md and output/fig_*.png

Run:  uv run --with duckdb --with pandas --with matplotlib --with tabulate python code/03_descriptives.py
"""
import os
import sys
import duckdb
import pandas as pd
import matplotlib.pyplot as plt

DATA_DIR = os.environ.get("IOWA_DATA_DIR", os.path.expanduser("~/mgt634_data/iowa_liquor"))
B = os.path.join(DATA_DIR, "build").replace("\\", "/")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "output")
os.makedirs(OUT, exist_ok=True)
try:  # Michal's chart style if available; plain matplotlib otherwise
    sys.path.insert(0, os.path.abspath(os.path.join(OUT, "..", "..", "..", "..")))
    import upshot_style as us
    us.use_style()
except Exception:
    pass
con = duckdb.connect()
q = lambda s: con.execute(s).df()
md = ["# Descriptives (auto-generated by code/03_descriptives.py)\n"]

# (a) yearly totals
yr = q(f"""SELECT year(month) AS year, ROUND(SUM(bottles)/1e6,1) AS m_bottles, ROUND(SUM(liters)/1e6,1) AS m_liters,
                  ROUND(SUM(dollars)/1e6,1) AS m_dollars_to_state, COUNT(DISTINCT item_no) AS items
           FROM '{B}/item_month.parquet' GROUP BY 1 ORDER BY 1""")
yr["state_margin_m"] = (yr["m_dollars_to_state"] / 3).round(1)          # margin = price/3 because price = 1.5 x cost
md += ["## Market size by year (duplicates removed)", yr.to_markdown(index=False),
       "\nState margin = dollars / 3 (price = 1.5 x supplier cost).\n"]

# (b) posted-price changes: compare each item's posted price with its previous month with sales
pc = q(f"""
    WITH x AS (SELECT item_no, month, price_posted, bottles,
                      LAG(price_posted) OVER (PARTITION BY item_no ORDER BY month) AS prev,
                      LAG(month) OVER (PARTITION BY item_no ORDER BY month) AS prev_month
               FROM '{B}/item_month.parquet')
    SELECT * FROM x WHERE prev IS NOT NULL AND date_diff('month', prev_month, month) = 1""")
pc["changed"] = (pc["price_posted"] - pc["prev"]).abs() > 0.005
pc["pct"] = pc["price_posted"] / pc["prev"] - 1
pc = pc[pc["month"] != "2025-11-01"]          # Nov 2025 = new ordering system (artificial price "changes"); excluded
by_year = pc.groupby(pc["month"].dt.year).agg(item_months=("changed", "size"), share_changed=("changed", "mean"),
                                              share_up=("pct", lambda s: (s > 0.005).mean()),
                                              share_down=("pct", lambda s: (s < -0.005).mean()))
by_cal = pc.groupby(pc["month"].dt.month)["changed"].mean().rename("share_changed")
md += ["## How often does an item's posted price change from one month to the next?",
       by_year.round(4).to_markdown(), "\n### By calendar month (all years)", by_cal.round(4).to_frame().T.to_markdown(index=False)]
vol_w = (pc.loc[pc.changed, "pct"].describe(percentiles=[.1, .25, .5, .75, .9])).round(3)
md += ["\n### Size of price changes (when they happen)", vol_w.to_frame("pct_change").T.to_markdown(index=False)]

fig, ax = plt.subplots(figsize=(9, 3.6))
ax.bar(by_cal.index, by_cal.values * 100, color="#2b6cb0")
ax.set_xticks(range(1, 13)); ax.set_xlabel("Calendar month"); ax.set_ylabel("% of items changing price")
ax.set_title("When do Iowa's posted liquor prices change? (2018-2025)", loc="left")
fig.tight_layout(); fig.savefig(os.path.join(OUT, "fig_price_change_timing.png"), dpi=150)

# (c) categories
cat = q(f"""SELECT i.category_name, COUNT(DISTINCT m.item_no) AS items, ROUND(SUM(m.bottles)/1e6,2) AS m_bottles,
                   ROUND(SUM(m.dollars)/1e6,1) AS m_dollars, ROUND(SUM(m.dollars)/SUM(m.bottles),2) AS avg_price
            FROM '{B}/item_month.parquet' m JOIN '{B}/items.parquet' i USING (item_no)
            GROUP BY 1 ORDER BY m_dollars DESC""")
md += ["\n## Categories (all years)", cat.to_markdown(index=False)]

open(os.path.join(OUT, "descriptives.md"), "w", encoding="utf-8").write("\n".join(md))
print("\n".join(md[:8]))
print(by_year.round(4).to_string()); print(by_cal.round(4).to_string()); print(vol_w.to_string())
